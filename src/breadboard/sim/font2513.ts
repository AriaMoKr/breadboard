/** The chart as above, one string a line: for checking a copy against it. */
export const FONT_2513_CHART: readonly string[] = CHART;

/**
 * FONT_2513[code][row]: the five outputs for a character code (0-63) and a row (0-7, from the top),
 * O1 in bit 0 to O5 in bit 4.
 */
export const FONT_2513: readonly (readonly number[])[] = Array.from({ length: 64 }, (_, code) =>
  Array.from({ length: 8 }, (_, r) => {
    const dots = CHART[(code >> 3) * 8 + r].split(' ')[code & 7];
    let v = 0;
    for (let k = 0; k < 5; k++) if (dots[k] === '#') v |= 1 << (4 - k);
    return v;
  }),
);

/** A character's six-bit code, as the TV Typewriter's six-bit ASCII has it: null if the 2513 has none. */
export function code2513(ch: string): number | null {
  const a = ch.toUpperCase().charCodeAt(0);
  return a >= 0x20 && a <= 0x5f ? a & 0x3f : null;
}

/** The character a six-bit code stands for. */
export const char2513 = (code: number): string => String.fromCharCode((code & 0x3f) < 0x20 ? 0x40 + (code & 0x3f) : code & 0x3f);
