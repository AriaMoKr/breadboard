// Runs after `vite build`: writes dist/sw.js, the service worker that keeps the app working
// offline after the first visit (and makes it installable). It caches every built file (not the
// zip) under a name made from their contents, so each new build replaces the old cache.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');
const name = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).name;

const files = [];
const walk = (d) => {
  for (const e of readdirSync(d, { withFileTypes: true })) {
    const p = join(d, e.name);
    if (e.isDirectory()) walk(p);
    else files.push(relative(dist, p).split(sep).join('/'));
  }
};
walk(dist);
const cached = files.filter((f) => f !== 'sw.js' && !f.endsWith('.zip') && f !== 'index.html').sort();
const hash = createHash('sha256');
for (const f of ['index.html', ...cached]) hash.update(f).update(readFileSync(join(dist, f)));
const cache = `${name}-${hash.digest('hex').slice(0, 12)}`;

// './' rather than 'index.html': some hosts redirect index.html to the folder, and a redirected
// response can't answer a page load.
const sw = `// Generated by scripts/sw-dist.mjs. Offline copy of the app.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(['./', ...cached], null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  const old = (k) => k.startsWith(${JSON.stringify(`${name}-`)}) && k !== CACHE;
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter(old).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // a page: fresh when online (a new build shows up at once), the cached copy offline
    // (vr.html is cached by its name, the app by './')
    e.respondWith(fetch(req).catch(async () => (await caches.match(req, { ignoreSearch: true })) ?? caches.match('./')));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit ?? fetch(req)));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`dist/sw.js  ${cache}, ${cached.length + 1} files cached`);
